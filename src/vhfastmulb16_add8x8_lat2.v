// =============================================================
// vhfastmulb16_add8x8_lat2 - сложение двух 8-бит чисел и вычитание 127
// Полностью конвейерный, латентность 2 такта
// =============================================================

module vhfastmulb16_add8x8_lat2 (
    input  wire        clk,
    input  wire        reset,
    input  wire        en,
    input  wire [7:0]  a,
    input  wire [7:0]  b,
    output reg  [8:0]  c
);

    // ============================================================================
    // Конвейер (2 стадии)
    //   стадия 1: c_add <= a + b
    //   стадия 2: c     <= c_add - 127
    // en_lat1 проходит вместе с данными (valid для стадии 2)
    // ============================================================================

    reg [8:0] c_add;    // Регистр суммы (стадия 1)
    reg       en_lat1;  // Valid для стадии 2

    always @(posedge clk) begin
        if (reset) begin
            c_add   <= 9'd0;
            c       <= 9'd0;
            en_lat1 <= 1'b0;
        end else begin
            // ---------------------------------------------------
            // Стадия 1: сложение a + b
            // При en=1 — загружаем новую сумму
            // При en=0 — удерживаем текущее значение (HOLD)
            // ---------------------------------------------------
            if (en) begin
                c_add <= {1'b0, a} + {1'b0, b};
            end
            // else: hold c_add (не обнуляем!)

            // ---------------------------------------------------
            // Стадия 2: вычитание 127 из суммы предыдущего такта
            // en_lat1 = en от предыдущего такта
            // При en_lat1=1 — вычисляем результат
            // При en_lat1=0 — удерживаем выход (HOLD)
            // ---------------------------------------------------
            if (en_lat1) begin
                c <= c_add - 9'd127;
            end
            // else: hold c (не обнуляем!)

            // ---------------------------------------------------
            // Пропуск en через конвейер
            // ---------------------------------------------------
            en_lat1 <= en;
        end
    end

endmodule