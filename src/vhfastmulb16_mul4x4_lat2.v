// File: vhfastmulb16_mul4x4_lat2.v
// Module: vhfastmulb16_mul4x4_lat2
// Multiplication of two 4-bit numbers, 2-stage pipeline
// Result latency: 2 clk
//
// Architecture:
//   - stage 1: 4 aligned partial products (a[i] ? b : 0) and
//     CSA level 1 (pp0 + pp1 + pp2 -> s1 + c1);
//   - stage 2: pp3 from registered operands, CSA level 2
//     (s1 + c1 + pp3 -> s2 + c2) and the final CPA (s2 + c2).
// Operator '*' is not used.
// ----------------------------------------------

module vhfastmulb16_mul4x4_lat2 (
    input  wire       clk,
    input  wire       reset,
    input  wire       en,
    input  wire [3:0] a,
    input  wire [3:0] b,
    output reg  [7:0] c
);

    // ============================================================================
    // Конвейер (2 стадии)
    //   стадия 1: PP + CSA-1  -> s1, c1 (регистры), a_lat/b_lat для pp3
    //   стадия 2: pp3 + CSA-2 + CPA -> c
    // en_lat1 проходит вместе с данными (valid для стадии 2)
    // ============================================================================

    // ------------------------------------------------------------------
    // Стадия 1 (комбинационная часть): частичные произведения и CSA-1
    // 10 бит на строку — запас под переносы CSA
    // ------------------------------------------------------------------
    wire [9:0] pp0 = {6'b000000, {4{a[0]}} & b};
    wire [9:0] pp1 = {5'b00000,  {4{a[1]}} & b, 1'b0};
    wire [9:0] pp2 = {4'b0000,   {4{a[2]}} & b, 2'b00};

    wire [9:0] g1 = (pp0 & pp1) | (pp0 & pp2) | (pp1 & pp2);
    wire [9:0] s1_calc = pp0 ^ pp1 ^ pp2;
    wire [9:0] c1_calc = {g1[8:0], 1'b0};

    // Регистры стадии 1
    reg [9:0] s1;       // сумма CSA-1
    reg [9:0] c1;       // перенос CSA-1
    reg [3:0] a_lat;    // a для формирования pp3 на стадии 2
    reg [3:0] b_lat;    // b для формирования pp3 на стадии 2
    reg       en_lat1;  // valid для стадии 2

    // ------------------------------------------------------------------
    // Стадия 2 (комбинационная часть): pp3, CSA-2 и финальный CPA
    // ------------------------------------------------------------------
    wire [9:0] pp3 = {3'b000, {4{a_lat[3]}} & b_lat, 3'b000};

    wire [9:0] g2 = (s1 & c1) | (s1 & pp3) | (c1 & pp3);
    wire [9:0] s2 = s1 ^ c1 ^ pp3;
    wire [9:0] c2 = {g2[8:0], 1'b0};

    // Максимальное произведение 15*15 = 225, поэтому sum[9:8] всегда 0.
    wire [9:0] sum = s2 + c2;
    wire [7:0] c_calc = sum[7:0];

    // ------------------------------------------------------------------
    // Синхронная логика конвейера
    // reset имеет приоритет над en и обнуляет все регистры стадий
    // ------------------------------------------------------------------
    always @(posedge clk) begin
        if (reset) begin
            s1      <= 10'd0;
            c1      <= 10'd0;
            a_lat   <= 4'd0;
            b_lat   <= 4'd0;
            en_lat1 <= 1'b0;
            c       <= 8'd0;
        end else begin
            // ---------------------------------------------------
            // Стадия 1: при en=1 — загрузка новой пары,
            // при en=0 — удержание (HOLD)
            // ---------------------------------------------------
            if (en) begin
                s1    <= s1_calc;
                c1    <= c1_calc;
                a_lat <= a;
                b_lat <= b;
            end

            // ---------------------------------------------------
            // Стадия 2: вычисление результата пары предыдущего такта
            // при en_lat1=1, иначе удержание выхода (HOLD)
            // ---------------------------------------------------
            if (en_lat1) begin
                c <= c_calc;
            end

            // ---------------------------------------------------
            // Пропуск en через конвейер
            // ---------------------------------------------------
            en_lat1 <= en;
        end
    end

endmodule
